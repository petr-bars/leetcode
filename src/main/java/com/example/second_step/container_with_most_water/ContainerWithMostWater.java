package com.example.second_step.container_with_most_water;

/**
 * <p>You are given an integer array height of length n. There are n vertical
 * lines drawn such that the two endpoints of the ith line are (i, 0) and
 * (i, height[i]).</p>
 *
 * <p>Find two lines that together with the x-axis form a container, such that
 * the container contains the most water. Return the maximum amount of water
 * a container can store. Notice that you may not slant the container.</p>
 *
 * <p>Дан массив height длины n, где height[i] — высота вертикальной линии
 * на позиции i. Найти две линии, которые вместе с осью X образуют контейнер,
 * вмещающий максимальное количество воды. Объём воды =
 * min(height[left], height[right]) × (right - left).</p>
 *
 * <p>Пример:<br>
 * Вход:  height = [1,8,6,2,5,4,8,3,7]<br>
 * Выход: 49<br>
 * Пояснение: максимум между линиями на позициях 1 (высота 8) и 8 (высота 7).
 * Объём = min(8,7) × (8-1) = 49.</p>
 *
 * <p>Паттерн:<br>
 * Два указателя навстречу + жадное движение с пропуском бесполезных линий.</p>
 *
 * <p>Именование переменных:<br>
 * left — указатель с начала массива, right — с конца. maxArea — текущий
 * максимум объёма. minHeight — высота более низкой из двух линий, она
 * определяет уровень воды. width — расстояние между указателями.
 * currentArea — объём для текущей пары.</p>
 *
 * <p>Идея:<br>
 * Начинаем с самой широкой позиции: left = 0, right = n - 1. На каждом
 * шаге считаем объём. Дальше ключевой момент: сдвигать нужно ту сторону,
 * у которой высота меньше, потому что именно она ограничивает объём.
 * Если сдвинуть большую — меньшая так и останется ограничителем,
 * а ширина уменьшится → объём не вырастет. Если сдвинуть меньшую — есть
 * шанс найти более высокую линию.</p>
 *
 * <p>В отличие от классического варианта, здесь сдвигаем не на один шаг,
 * а пропускаем сразу группы бесполезных линий. Все линии, высота которых
 * не больше minHeight, не могут улучшить результат: если они станут
 * ограничителем, объём будет не больше текущего, а ширина уменьшится.
 * Значит, их можно пропустить целиком. Аналогичный приём используется
 * в задаче 3Sum для пропуска дубликатов.</p>
 *
 * <p>Логика и шаги:</p>
 * <ul>
 *   <li>Инициализация:
 *       <ul>
 *         <li>left = 0 — начало массива.</li>
 *         <li>right = n - 1 — конец массива.</li>
 *         <li>maxArea = 0.</li>
 *       </ul>
 *   </li>
 *   <li>Пока left &lt; right:
 *       <ul>
 *         <li>minHeight = min(height[left], height[right]). Высота воды
 *             ограничена более низкой линией.</li>
 *         <li>width = right - left.</li>
 *         <li>currentArea = minHeight * width.</li>
 *         <li>maxArea = max(maxArea, currentArea).</li>
 *         <li>Пропускаем бесполезные линии слева: пока left &lt; right
 *             и height[left] &lt;= minHeight — left++. Все эти линии
 *             не выше minHeight, они не могут стать лучшим ограничителем.</li>
 *         <li>Пропускаем бесполезные линии справа: пока left &lt; right
 *             и height[right] &lt;= minHeight — right--. Симметрично.</li>
 *         <li>Если обе стороны прошли проверку — оба указателя сдвинулись
 *             (хотя бы на 1). Это нормально, продолжаем.</li>
 *       </ul>
 *   </li>
 *   <li>Возвращаем maxArea.</li>
 * </ul>
 *
 * <p>Ключевые тонкости:</p>
 * <ul>
 *   <li>Условие height[left] &lt;= minHeight, а не &lt;. Случай равенства
 *       тоже бесполезен: если линия равна minHeight, она не улучшит
 *       ограничитель, а ширина уменьшится. Значит, можно пропустить.</li>
 *   <li>Пропускаем с обеих сторон, а не только с одной. Классика двигает
 *       только меньшую сторону. Здесь мы дополнительно пропускаем все
 *       линии с обеих сторон, которые не выше minHeight. Это безопасно,
 *       потому что ни одна из них не может улучшить результат.</li>
 *   <li>Два while идут последовательно, не вложены. Сначала пропускаем
 *       слева, потом справа. Порядок не важен, потому что условия
 *       независимы.</li>
 *   <li>Условие left &lt; right в каждом while — защита от выхода за
 *       границы и от зацикливания. Без него можно уйти в минус или
 *       наткнуться на ArrayIndexOutOfBoundsException.</li>
 *   <li>Если оба указателя указывают на линии равной высоты minHeight,
 *       оба while сработают и оба указателя сдвинутся. Это может
 *       показаться избыточным, но корректно: обе линии бесполезны для
 *       будущих улучшений.</li>
 *   <li>maxArea = 0 — начальное значение. Все высоты положительные,
 *       поэтому первый же посчитанный объём будет больше 0.</li>
 *   <li>Оптимизация не меняет асимптотику. Время O(n), память O(1).
 *       Она лишь уменьшает число итераций внешнего цикла: за один проход
 *       while пропускается несколько бесполезных линий.</li>
 *   <li>Не путать с Trapping Rain Water: там суммарный объём воды над
 *       всеми столбцами, здесь — объём одного контейнера между двумя
 *       линиями.</li>
 *   <li>Пустой массив или массив из одного элемента — цикл не выполнится,
 *       вернётся 0. По условиям LeetCode n &gt;= 2.</li>
 * </ul>
 *
 * <p>Проверки:</p>
 * <ul>
 *   <li>height = [1,8,6,2,5,4,8,3,7] → 49.</li>
 *   <li>height = [1,1] → 1. Минимальный размер.</li>
 *   <li>height = [1,2,1] → 2.</li>
 *   <li>height = [4,3,2,1,4] → 16. Пара линий по краям.</li>
 *   <li>height = [1,2,4,3] → 4.</li>
 *   <li>height = [1,1,1,1] → 3. Все одинаковые, ширина решает.</li>
 *   <li>height = [1,2] → 1.</li>
 * </ul>
 *
 * <p>Сложность:<br>
 * Время: O(n) — каждый указатель суммарно двигается не более n раз.<br>
 * Память: O(1) — только указатели и временные переменные.</p>
 */
public class ContainerWithMostWater {
    public static void main(String[] args) {
        int[] height = new int[]{1, 8, 6, 2, 5, 4, 8, 3, 7};

        System.out.println(maxArea(height));
    }

    public static int maxArea(int[] height) {
        int left = 0;
        int right = height.length - 1;
        int maxArea = 0;

        while (left < right) {
            int minHeight = Math.min(height[left], height[right]);
            int width = right - left;
            int currentArea = minHeight * width;
            maxArea = Math.max(maxArea, currentArea);

            /*Сдвигаемся не на один шаг как в классическом решении, а пропускаем сразу группами.
             * Аналогичным способом отрабатывали поиск дубликатов в задаче 3Sum
             * тем самым избегаем лишних шагов*/
            while (left < right && height[left] <= minHeight) {
                left++;
            }
            while (left < right && height[right] <= minHeight) {
                right--;
            }
        }

        return maxArea;
    }
}
