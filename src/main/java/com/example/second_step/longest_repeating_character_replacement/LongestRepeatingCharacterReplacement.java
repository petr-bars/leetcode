package com.example.second_step.longest_repeating_character_replacement;

/**
 * <p>You are given a string s and an integer k. You can choose any character
 * of the string and change it to any other uppercase English character. You
 * can perform this operation at most k times.</p>
 *
 * <p>Return the length of the longest substring containing the same letter
 * you can get after performing the above operations.</p>
 *
 * <p>Дана строка s и число k. Можно заменить не более k символов на любые
 * другие заглавные английские буквы. Найти длину самой длинной подстроки,
 * которую можно получить, если все символы в ней сделать одинаковыми.</p>
 *
 * <p>Пример:<br>
 * Вход:  s = "ABAB", k = 2<br>
 * Выход: 4<br>
 * Пояснение: заменяем две 'A' на 'B' → "BBBB", длина 4.</p>
 *
 * <p>Пример:<br>
 * Вход:  s = "AABABBA", k = 1<br>
 * Выход: 4<br>
 * Пояснение: заменяем одну 'A' на 'B' → "AABBBBA", подстрока "BBBB" длины 4.</p>
 *
 * <p>Паттерн:<br>
 * Sliding window (variable) + подсчёт частот внутри окна.</p>
 *
 * <p>Именование переменных:<br>
 * left и right — границы окна. freq — массив на 26, частоты символов
 * внутри текущего окна. maxFreq — исторический максимум частоты одного
 * символа в окне (только растёт). maxLength — длина самой длинной валидной
 * подстроки за весь проход. windowLen — текущая длина окна. currentChar —
 * символ на позиции right.</p>
 *
 * <p>Идея:<br>
 * Ищем самую длинную подстроку, которую можно сделать однородной, заменив
 * не более k символов. Ключевое наблюдение: чтобы сделать окно однородным,
 * нужно заменить все символы, кроме самого частого. Количество замен =
 * длина окна − частота самого частого символа. Если это число ≤ k — окно
 * валидное, можно расширять. Если > k — замен не хватает, надо сжимать
 * слева.</p>
 *
 * <p>Формула:</p>
 * <ul>
 *   <li>Замен_нужно = длина_окна − maxFreq.</li>
 *   <li>Окно валидное, если замен_нужно &lt;= k.</li>
 *   <li>При нарушении: freq[s.charAt(left)]--, left++.</li>
 * </ul>
 *
 * <p>Логика и шаги:</p>
 * <ul>
 *   <li>Инициализация: left = 0, maxFreq = 0, maxLength = 0, freq = new int[26].</li>
 *   <li>Проход right от 0 до n-1:
 *       <ul>
 *         <li>currentChar = s.charAt(right). freq[currentChar - 'A']++.</li>
 *         <li>maxFreq = max(maxFreq, freq[currentChar - 'A']).</li>
 *         <li>windowLen = right - left + 1.</li>
 *         <li>Если windowLen - maxFreq &gt; k — окно невалидное, сжимаем:
 *             freq[s.charAt(left) - 'A']--, left++.</li>
 *         <li>maxLength = max(maxLength, right - left + 1).</li>
 *       </ul>
 *   </li>
 *   <li>Возвращаем maxLength.</li>
 * </ul>
 *
 * <p>Ключевая тонкость (трюк с maxFreq):</p>
 * <ul>
 *   <li>При сжатии окна мы НЕ уменьшаем и НЕ пересчитываем maxFreq.
 *       Это не баг, а оптимизация.</li>
 *   <li>Почему работает: мы ищем окно длиннее уже найденного рекорда.
 *       Если maxFreq остался завышенным, условие валидности станет строже,
 *       и окно просто не сможет разрастись до размера, превышающего наш
 *       текущий рекорд. Старый рекорд не теряется.</li>
 *   <li>Что это даёт: не нужно пересчитывать максимум по массиву частот
 *       на каждом шаге. Иначе было бы O(26·n), что для фиксированного
 *       алфавита тоже O(n), но с большей константой.</li>
 * </ul>
 *
 * <p>Ключевые тонкости:</p>
 * <ul>
 *   <li>Сжатие через if, а не while. Окно никогда не сжимается больше чем
 *       на 1 за итерацию. Его размер монотонно не убывает — либо растёт,
 *       либо стоит на месте. Этого достаточно, потому что maxLength уже
 *       зафиксировал лучший размер, и меньше он не станет.</li>
 *   <li>Проверка windowLen - maxFreq &gt; k, а не &lt;. Замен не хватает
 *       именно когда их больше k. Равенство — окно ещё валидно.</li>
 *   <li>maxFreq обновляется до проверки, потому что мы только что добавили
 *       символ и его частота могла стать новой максимальной.</li>
 *   <li>Массив на 26 — для заглавных латинских букв ('A'–'Z'). Если бы
 *       были строчные или другие символы, размер нужно увеличить.</li>
 *   <li>Вычитание 'A' из символа даёт индекс от 0 до 25. Работает потому,
 *       что коды заглавных букв в ASCII идут подряд.</li>
 *   <li>maxLength обновляется на каждом шаге, а не только при валидном
 *       окне. После сжатия окно уже валидное (или его размер не изменился),
 *       и длину можно зафиксировать.</li>
 *   <li>Если k больше длины строки — можно сделать всю строку однородной.
 *       Ответ = n. Алгоритм это обрабатывает: сжатие ни разу не сработает,
 *       maxLength дойдёт до n.</li>
 * </ul>
 *
 * <p>Проверки:</p>
 * <ul>
 *   <li>s = "ABAB", k = 2 → 4. Вся строка.</li>
 *   <li>s = "AABABBA", k = 1 → 4. Подстрока "BBBB".</li>
 *   <li>s = "A", k = 0 → 1. Один символ.</li>
 *   <li>s = "AA", k = 0 → 2. Все одинаковые.</li>
 *   <li>s = "AB", k = 0 → 1. Все разные, одну замену не хватает.</li>
 *   <li>s = "AB", k = 1 → 2. Одной замены хватает.</li>
 *   <li>s = "AAAA", k = 0 → 4. Всё уже одинаково.</li>
 *   <li>s = "ABCD", k = 0 → 1. Все разные.</li>
 *   <li>s = "ABCD", k = 3 → 4. Трёх замен хватает.</li>
 *   <li>s = "BAAAB", k = 2 → 5. Вся строка.</li>
 *   <li>s = "ABBB", k = 0 → 3. Подстрока "BBB".</li>
 * </ul>
 *
 * <p>Сложность:<br>
 * Время: O(n) — right и left двигаются только вперёд.<br>
 * Память: O(1) — массив фиксированного размера на 26 символов.</p>
 */
public class LongestRepeatingCharacterReplacement {
    public static void main(String[] args) {
        String s = "AABABB";
        int k = 1;

        System.out.println(characterReplacement(s, k));
    }

    public static int characterReplacement(String s, int k) {
        // Начальное состояние: окно пустое, обе границы в начале, рекорд длины = 0
        int left = 0;
        int maxFreq = 0;
        int maxLength = 0;
        int[] count = new int[26];

        // Двигаем правую границу окна, захватывая новые символы строки
        for (int right = 0; right < s.length(); right++) {
            char current = s.charAt(right);

            // 1. Расширение окна: добавляем символ и считаем, сколько раз он уже встречался в окне
            count[current - 'A']++;

            // 2. Обновление максимума: проверяем, не стал ли текущий символ самым частым в окне
            maxFreq = Math.max(maxFreq, count[current - 'A']);

            // 3. Проверка лимита замен:
            // (длина окна) - (самый частый символ) = количество символов, которые нужно заменить.
            // Если это число строго больше k, значит, мы превысили лимит замен. Окно "сломалось".
            while ((right - left + 1) - maxFreq > k) {

                // 4. Сжатие окна: чтобы починить его, убираем символ из левой границы
                // (уменьшаем его счетчик) и сдвигаем левую границу вправо.
                // Делаем это до тех пор, пока количество требуемых замен не влезет в лимит k.
                count[s.charAt(left) - 'A']--;
                left++;
            }

            // 5. Фиксация максимальной последовательности: окно снова валидно.
            // Сравниваем его текущую длину с лучшим результатом.
            maxLength = Math.max(maxLength, right - left + 1);
        }

        return maxLength;
    }
}
