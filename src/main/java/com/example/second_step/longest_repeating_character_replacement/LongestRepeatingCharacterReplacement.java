package com.example.second_step.longest_repeating_character_replacement;


/**
 * You are given a string s and an integer k.
 * You can choose any character of the string and change it to any other uppercase English character.
 * You can perform this operation at most k times.
 * Return the length of the longest substring containing the same letter you can get after performing
 * the above operations.
 * <p>
 * Дана строка s и число k. Можно заменить не более k символов на любые другие. Найти длину самой длинной подстроки,
 * которую можно получить, если все символы в ней сделать одинаковыми.
 * Пример:
 * Вход:  s = "ABAB", k = 2
 * Выход: 4
 * Пояснение: заменяем две 'A' на 'B' → "BBBB", длина 4.
 * <p>
 * Паттерн:
 * Sliding window (variable) — окно переменного размера + подсчёт частот внутри окна.
 * <p>
 * Логика и шаги:
 * 1. Инициализация: Заводим скользящее окно (левая и правая границы). Храним частоты символов
 * внутри окна и исторический максимум частоты одного символа.
 * 2. Расширение: Двигаем правую границу, добавляя новый символ. Увеличиваем его частоту.
 * Если частота текущего символа превысила наш исторический максимум — обновляем его.
 * 3. Проверка и сжатие: Считаем, сколько замен нужно (длина окна минус макс. частота).
 * Если замен нужно больше, чем k, окно невалидно. Сдвигаем левую границу вправо,
 * уменьшая частоту выходящего символа, пока окно снова не станет валидным.
 * 4. Фиксация ответа: После того как окно стало валидным, сравниваем его текущую длину
 * с лучшим найденным результатом и обновляем рекорд.
 * <p>
 * Ключевая тонкость (Трюк с maxFreq):
 * При сжатии окна мы НЕ уменьшаем и НЕ пересчитываем максимальную частоту.
 * Это не баг, а важная оптимизация. Мы ищем окно ДЛИННЕЕ уже найденного рекорда.
 * Если maxFreq остался завышенным, условие валидности станет строже, и окно просто
 * не сможет разрастись до размера, превышающего наш текущий рекорд. Это избавляет нас от
 * необходимости искать максимум в массиве за O(26) на каждом шаге.
 * <p>
 * Сложность:
 * Время: O(n) — правая и левая границы двигаются только вперед.
 * Память: O(1) — массив фиксированного размера на 26 символов.
 */
public class LongestRepeatingCharacterReplacement {
    public static void main(String[] args) {
        String s = "AABABB";
        int k = 1;

        System.out.println(characterReplacement(s, k));
    }

    public static int characterReplacement(String s, int k) {
        // Начальное состояние: окно пустое, обе границы в начале, рекорд длины = 0
        int left = 0;
        int maxFreq = 0;
        int best = 0;
        int[] count = new int[26];

        // Двигаем правую границу окна, захватывая новые символы строки
        for (int right = 0; right < s.length(); right++) {
            char current = s.charAt(right);

            // 1. Расширение окна: добавляем символ и считаем, сколько раз он уже встречался в окне
            count[current - 'A']++;

            // 2. Обновление максимума: проверяем, не стал ли текущий символ самым частым в окне
            maxFreq = Math.max(maxFreq, count[current - 'A']);

            // 3. Проверка лимита замен:
            // (длина окна) - (самый частый символ) = количество символов, которые нужно заменить.
            // Если это число строго больше k, значит, мы превысили лимит замен. Окно "сломалось".
            while ((right - left + 1) - maxFreq > k) {

                // 4. Сжатие окна: чтобы починить его, убираем символ из левой границы
                // (уменьшаем его счетчик) и сдвигаем левую границу вправо.
                // Делаем это до тех пор, пока количество требуемых замен не влезет в лимит k.
                count[s.charAt(left) - 'A']--;
                left++;
            }

            // 5. Фиксация рекорда: окно снова валидно. Сравниваем его текущую длину с лучшим результатом.
            best = Math.max(best, right - left + 1);
        }

        return best;
    }
}
