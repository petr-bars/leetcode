package com.example.second_step.find_all_anagrams_in_a_string;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

/**
 * Given two strings s and p, return an array of all the start indices of p's anagrams in s.
 * You may return the answer in any order.
 * <p>
 * Даны две строки s и p. Найти все начальные индексы подстрок в s, которые являются анаграммами p.
 * Анаграмма — перестановка букв. abc и bca — анаграммы.
 * Пример:
 * Вход:  s = "cbaebabacd", p = "abc"
 * Выход: [0, 6]
 * Пояснение:
 * индекс 0 → "cba" — анаграмма "abc"
 * индекс 6 → "bac" — анаграмма "abc"
 * <p>
 * Паттерн:
 * Fixed sliding window — окно фиксированного размера + подсчёт частот внутри.
 * <p>
 * Идея:
 * Анаграмма означает, что набор букв и их частоты в подстроке должны в точности совпадать с частотами в строке p.
 * Порядок букв не важен. Значит, нам нужно найти все окна в строке s длиной ровно p.length(),
 * у которых частоты символов идентичны частотам символов в p.
 * <p>
 * Логика и шаги:
 * 1. Инициализация эталона: Считаем, сколько раз каждая буква встречается в строке p. Это наш массив-эталон.
 * 2. Формирование первого окна: Берем первые m символов строки s (где m — длина p) и считаем их частоты в отдельный массив.
 * 3. Проверка первого окна: Сравниваем частоты первого окна с эталоном. Если массивы полностью совпадают,
 * значит, подстрока начинается с индекса 0. Добавляем 0 в список результатов.
 * 4. Сдвиг окна: Начинаем двигать окно вправо по одному символу за раз.
 * На каждом шаге мы добавляем в окно новый символ, который встал под правую границу,
 * и удаляем символ, который выпал из окна слева.
 * 5. Обновление результата: После каждого сдвига окна мы сравниваем его частоты с эталоном.
 * Если они совпадают, мы вычисляем начальный индекс текущего окна и добавляем его в результат.
 * Начальный индекс вычисляется просто: позиция правой границы минус длина окна плюс один.
 * <p>
 * Ключевая тонкость (Фиксированное окно и индексы):
 * В отличие от задач с переменным окном, здесь окно всегда имеет строго фиксированную длину.
 * Мы никогда не растягиваем и не сжимаем его — мы только сдвигаем его вправо.
 * Поскольку длина окна постоянна, его левая граница (начальный индекс) всегда жестко привязана к правой.
 * Именно этот вычисленный начальный индекс мы и сохраняем, когда находим совпадение частот.
 * <p>
 * Сложность:
 * Время: O(n) — мы проходим по строке s один раз. На каждом шаге мы сдвигаем окно за O(1),
 * но сравниваем два массива частот за O(26). Итоговое время O(26 * n), что для фиксированного алфавита равно O(n).
 * Память: O(1) — мы храним только два массива частот фиксированного размера (на 26 букв).
 */
public class FindAllAnagramsInAString {
    public static void main(String[] args) {
        String s = "cbaebabacd";
        String p = "abc";

        System.out.println(findAnagrams(s, p));
    }

    public static List<Integer> findAnagrams(String s, String p) {
        List<Integer> result = new ArrayList<>();
        int lengthS = s.length();
        int lengthP = p.length();

        if (lengthS < lengthP) {
            return result;
        }

        // Заполняем шаблон на который будем ориентироваться
        int[] freqP = new int[26];
        for (char symbol : p.toCharArray()) {
            freqP[symbol - 'a']++;
        }

        // Инициализируем первое фиксированное окно
        int[] freqW = new int[26];
        for (int index = 0; index < lengthP; index++) {
            freqW[s.charAt(index) - 'a']++;
        }

        // Если совпали значит начальный индекс 0
        if (Arrays.equals(freqP, freqW)) {
            result.add(0);
        }

        for (int right = lengthP; right < lengthS; right++) {
            // Инкримент текущего символа
            freqW[s.charAt(right) - 'a']++;
            // Дикримент лишнего левого которое выпадает из размера окна
            freqW[s.charAt(right - lengthP) - 'a']--;

            if (Arrays.equals(freqP, freqW)) {
                result.add(right - lengthP + 1);
            }
        }
        return result;
    }
}
