package com.example.second_step.move_zeroes;

import java.util.Arrays;

/**
 * <p>Given an integer array nums, move all 0's to the end of it while
 * maintaining the relative order of the non-zero elements.</p>
 *
 * <p>Note that you must do this in-place without making a copy of the array.</p>
 *
 * <p>Дан массив nums. Переместить все нули в конец, сохранив порядок
 * остальных элементов. Всё делается на месте, без создания нового массива.</p>
 *
 * <p>Пример:<br>
 * Вход:  nums = [0,1,0,3,12]<br>
 * Выход: [1,3,12,0,0]</p>
 *
 * <p>Пример:<br>
 * Вход:  nums = [0]<br>
 * Выход: [0]</p>
 *
 * <p>Паттерн:<br>
 * Read/Write pointers — два указателя: один читает, другой пишет.</p>
 *
 * <p>Именование переменных:<br>
 * read — указатель, который идёт по всему массиву и читает каждый элемент.
 * write — указатель, который показывает, куда положить следующий ненулевой
 * элемент. Он всегда не опережает read. num — текущий элемент в цикле.</p>
 *
 * <p>Идея:<br>
 * Идём по массиву одним указателем read. Второй указатель write показывает,
 * куда положить следующий ненулевой элемент. Если nums[read] != 0 — это
 * ненулевой, кладём его на позицию write, сдвигаем write вперёд. Если ноль —
 * пропускаем, ничего не делаем. После прохода все ненулевые стоят в начале
 * в исходном порядке, а хвост массива от write до конца заполняем нулями.</p>
 *
 * <p>Формула:</p>
 * <ul>
 *   <li>write = счётчик ненулевых.</li>
 *   <li>на каждый read: если nums[read] != 0 → nums[write] = nums[read],
 *       write++.</li>
 *   <li>после прохода: nums[write..n-1] = 0.</li>
 * </ul>
 *
 * <p>Логика и шаги:</p>
 * <ul>
 *   <li>Инициализация: write = 0.</li>
 *   <li>Первый проход, read от 0 до n-1:
 *       <ul>
 *         <li>Если nums[read] != 0 — копируем nums[read] в nums[write],
 *             увеличиваем write.</li>
 *         <li>Если nums[read] == 0 — ничего не делаем.</li>
 *       </ul>
 *   </li>
 *   <li>Второй проход, index от write до n-1:
 *       <ul>
 *         <li>nums[index] = 0. Заливаем хвост нулями.</li>
 *       </ul>
 *   </li>
 * </ul>
 *
 * <p>Ключевые тонкости:</p>
 * <ul>
 *   <li>Порядок ненулевых сохраняется. Мы копируем их в том же порядке,
 *       в котором читаем, поэтому относительный порядок не меняется.</li>
 *   <li>write всегда не опережает read. Значит, nums[write] = nums[read]
 *       никогда не затирает ещё не прочитанный элемент. Всё, что левее
 *       write, уже обработано; всё, что правее read, ещё не читали.</li>
 *   <li>read идёт по всему массиву, включая позиции до write. Это нормально:
 *       элементы до write либо уже скопированы, либо нули. Ничего не ломается.</li>
 *   <li>Если бы не второй проход с заливкой нулей, в массиве остались бы
 *       «хвосты» старых ненулевых значений. Например, [0,1,0,3,12] после
 *       первого прохода стал бы [1,3,12,3,12] — хвост 3,12 надо затереть
 *       нулями.</li>
 *   <li>Второй проход обязателен, потому что нельзя просто «удалить»
 *       элементы из массива фиксированной длины. Всё, что правее write,
 *       заливаем нулями вручную.</li>
 *   <li>Можно объединить два прохода в один: во время первого прохода
 *       после копирования nums[write] сразу ставить nums[read] = 0 (если
 *       read != write). Но это усложняет код, а выигрыш нулевой. Текущий
 *       вариант с двумя проходами читается чище.</li>
 *   <li>Если нулей нет, write дойдёт до n, второй проход не выполнится.
 *       Если все нули, write останется 0, второй проход зальёт весь массив
 *       нулями (он уже из нулей).</li>
 *   <li>Пустой массив — оба цикла не выполняются, массив остаётся пустым.</li>
 *   <li>Массив из одного элемента — если ноль, write останется 0, второй
 *       проход поставит 0 (он там уже есть). Если ненулевой, write = 1,
 *       второй проход не выполнится.</li>
 * </ul>
 *
 * <p>Проверки:</p>
 * <ul>
 *   <li>nums = [0,1,0,3,12] → [1,3,12,0,0].</li>
 *   <li>nums = [0] → [0].</li>
 *   <li>nums = [1] → [1].</li>
 *   <li>nums = [0,0,0] → [0,0,0]. Все нули.</li>
 *   <li>nums = [1,2,3] → [1,2,3]. Нулей нет.</li>
 *   <li>nums = [1,0,1] → [1,1,0].</li>
 *   <li>nums = [0,0,1] → [1,0,0].</li>
 *   <li>nums = [1,0,0] → [1,0,0].</li>
 *   <li>nums = [1,2,0,0,3,4] → [1,2,3,4,0,0].</li>
 *   <li>nums = [] → []. Пустой массив.</li>
 * </ul>
 *
 * <p>Сложность:<br>
 * Время: O(n) — первый проход O(n) на перенос ненулевых, второй O(n)
 *       на заливку нулей. Суммарно O(n).<br>
 * Память: O(1) — только два указателя, работа на месте.</p>
 */
public class MoveZeroes {
    public static void main(String[] args) {
        int[] nums = new int[]{0, 1, 0, 3, 12};
        moveZeroes(nums);
        System.out.println(Arrays.toString(nums));
    }

    public static void moveZeroes(int[] nums) {
        int write = 0;
        for (int read = 0; read < nums.length; read++) {
            if (nums[read] != 0) {
                nums[write] = nums[read];
                write++;
            }
        }

        while (write < nums.length) {
            nums[write++] = 0;
        }
    }
}
