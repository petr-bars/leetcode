package com.example.second_step.three_sum;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

/**
 * <p>Given an integer array nums, return all the triplets [nums[i], nums[j],
 * nums[k]] such that i != j, i != k, and j != k, and nums[i] + nums[j] +
 * nums[k] == 0.</p>
 *
 * <p>Notice that the solution set must not contain duplicate triplets.</p>
 *
 * <p>Дан массив nums. Вернуть все уникальные тройки [nums[i], nums[j],
 * nums[k]] такие, что i != j != k и nums[i] + nums[j] + nums[k] = 0.
 * В ответе не должно быть дублирующихся троек.</p>
 *
 * <p>Пример:<br>
 * Вход:  nums = [-1,0,1,2,-1,-4]<br>
 * Выход: [[-1,-1,2],[-1,0,1]]</p>
 *
 * <p>Пример:<br>
 * Вход:  nums = [0,1,1]<br>
 * Выход: []<br>
 * Пояснение: единственная тройка [0,1,1] не даёт в сумме 0.</p>
 *
 * <p>Пример:<br>
 * Вход:  nums = [0,0,0]<br>
 * Выход: [[0,0,0]]</p>
 *
 * <p>Паттерн:<br>
 * Сортировка + два указателя + пропуск дубликатов.</p>
 *
 * <p>Именование переменных:<br>
 * nums — входной массив. result — список итоговых троек. index — индекс
 * первого элемента тройки во внешнем цикле. left и right — указатели
 * для поиска пары внутри отрезка nums[index+1..n-1]. sum — сумма тройки
 * nums[index] + nums[left] + nums[right].</p>
 *
 * <p>Идея:<br>
 * Наивно — три вложенных цикла, O(n³). Но задача сводится к Two Sum II,
 * если зафиксировать первый элемент. Сортируем массив, идём внешним циклом
 * по index — это первый элемент тройки. Для каждого index остаётся найти
 * два числа в nums[index+1..n-1], сумма которых = -nums[index]. Это уже
 * Two Sum II — два указателя навстречу. Сортировка даёт порядок, который
 * позволяет двигать указатели осмысленно. Плюс она группирует одинаковые
 * числа рядом, что даёт возможность пропускать дубликаты на всех трёх
 * уровнях: index, left, right.</p>
 *
 * <p>Логика и шаги:</p>
 * <ul>
 *   <li>Сортировка:
 *       <ul>
 *         <li>Arrays.sort(nums). После этого одинаковые числа идут подряд,
 *             а массив отсортирован по возрастанию — это база для двух
 *             указателей.</li>
 *       </ul>
 *   </li>
 *   <li>Внешний цикл по index от 0 до n-3:
 *       <ul>
 *         <li>Пропуск дубликатов index: если index &gt; 0 и nums[index] ==
 *             nums[index-1] — continue. Тройки с этим числом уже были
 *             найдены на прошлой итерации.</li>
 *         <li>left = index + 1, right = n - 1. Ищем пару в оставшейся
 *             части массива.</li>
 *       </ul>
 *   </li>
 *   <li>Внутренний цикл while (left &lt; right):
 *       <ul>
 *         <li>sum = nums[index] + nums[left] + nums[right].</li>
 *         <li>Если sum == 0:
 *             <ul>
 *               <li>Добавляем тройку [nums[index], nums[left], nums[right]]
 *                   в result.</li>
 *               <li>Пропускаем дубликаты left: while (left &lt; right &&
 *                   nums[left] == nums[left+1]) left++.</li>
 *               <li>Пропускаем дубликаты right: while (left &lt; right &&
 *                   nums[right] == nums[right-1]) right--.</li>
 *               <li>После пропуска обязательно left++ и right--, иначе
 *                   зациклимся или получим дубликат.</li>
 *             </ul>
 *         </li>
 *         <li>Если sum &lt; 0 → left++. Сумма слишком маленькая, надо
 *             увеличить — берём большее число слева.</li>
 *         <li>Если sum &gt; 0 → right--. Сумма слишком большая, надо
 *             уменьшить — берём меньшее число справа.</li>
 *       </ul>
 *   </li>
 *   <li>Возвращаем result.</li>
 * </ul>
 *
 * <p>Ключевые тонкости:</p>
 * <ul>
 *   <li>Сортировка обязательна. Без неё два указателя не работают: нельзя
 *       понять, куда двигать left или right.</li>
 *   <li>Пропуск дубликатов на трёх уровнях. Без него в ответ попадут
 *       одинаковые тройки, что запрещено условием. Пропуск на уровне
 *       index — через сравнение с предыдущим. На уровне left и right —
 *       через while, потому что там может быть несколько одинаковых
 *       чисел подряд.</li>
 *   <li>Пропуск дубликатов left и right делается только после нахождения
 *       тройки (внутри ветки sum == 0). Если бы делали на каждой
 *       итерации, пропустили бы часть валидных пар.</li>
 *   <li>После пропуска дубликатов обязательно left++ и right--. Потому
 *       что while останавливается на последнем дубле, а не за ним.
 *       left++ перешагивает через этот дубль на новое число.</li>
 *   <li>Условие left &lt; right в while пропуска дубликатов — защита
 *       от выхода за границы. Без него можно упасть на ArrayIndexOutOfBounds
 *       или зациклиться.</li>
 *   <li>Внутренний while работает по отрезку nums[index+1..n-1], а не по
 *       всему массиву. Это гарантирует, что элементы не повторяются
 *       (i != j != k).</li>
 *   <li>List.of(nums[index], nums[left], nums[right]) создаёт иммутабельный
 *       список. Для LeetCode нормально, потому что никто не мутирует
 *       результат. Если бы требовалось изменять — нужен
 *       new ArrayList&lt;&gt;(List.of(...)).</li>
 *   <li>Пустой массив или массив из двух элементов — внешний цикл
 *       не выполнится или выполнится один раз без результата. Вернётся
 *       пустой список.</li>
 *   <li>Все числа одинаковые (например, [0,0,0,0]) — пропуск дубликатов
 *       index отсечёт всё, кроме первой итерации. На первой найдётся
 *       тройка [0,0,0], потом пропуск left и right закроет внутренний
 *       цикл. В ответе одна тройка, как и должно быть.</li>
 * </ul>
 *
 * <p>Проверки:</p>
 * <ul>
 *   <li>nums = [-1,0,1,2,-1,-4] → [[-1,-1,2],[-1,0,1]].</li>
 *   <li>nums = [0,1,1] → []. Нет троек с суммой 0.</li>
 *   <li>nums = [0,0,0] → [[0,0,0]].</li>
 *   <li>nums = [0,0,0,0] → [[0,0,0]]. Одна тройка, дубликаты
 *       отсеиваются.</li>
 *   <li>nums = [1,2,-2,-1] → [].</li>
 *   <li>nums = [-1,0,1] → [[-1,0,1]]. Минимальный валидный случай.</li>
 *   <li>nums = [-2,0,1,1,2] → [[-2,0,2],[-2,1,1]].</li>
 *   <li>nums = [-4,-2,-2,-2,0,1,2,2,2,3,3,4,4,6,6] →
 *       несколько троек, дубликаты отсеиваются.</li>
 *   <li>nums = [] → []. Пустой массив.</li>
 *   <li>nums = [0] → []. Один элемент.</li>
 *   <li>nums = [0,0] → []. Два элемента, тройку не собрать.</li>
 * </ul>
 *
 * <p>Сложность:<br>
 * Время: O(n²) — сортировка O(n log n), внешний цикл O(n), внутренний
 *       while O(n). Итого O(n²).<br>
 * Память: O(1) дополнительной (не считая выходного списка и места под
 *         сортировку).</p>
 */
public class ThreeSum {
    public static void main(String[] args) {
        int[] nums = new int[]{-1, 0, 1, 2, -1, -4};

        System.out.println(threeSum(nums));
    }

    public static List<List<Integer>> threeSum(int[] nums) {
        List<List<Integer>> result = new ArrayList<>();
        if (nums == null || nums.length < 3) {
            return result;
        }

        Arrays.sort(nums);

        for (int index = 0; index < nums.length - 2; index++) {
            if (index > 0 && nums[index] == nums[index - 1]) {
                continue;
            }

            int left = index + 1;
            int right = nums.length - 1;
            while (left < right) {
                int sum = nums[index] + nums[left] + nums[right];
                if (sum == 0) {
                    result.add(new ArrayList<>(List.of(nums[index], nums[left], nums[right])));

                    // Пропускаем дубликаты у left (сдвигаем, пока одинаковые).
                    while (left < right && nums[left] == nums[left + 1]) {
                        left++;
                    }
                    // Пропускаем дубликаты у right (сдвигаем, пока одинаковые).
                    while (left < right && nums[right] == nums[right - 1]) {
                        right--;
                    }

                    left++;
                    right--;
                } else if (sum < 0) {
                    left++;
                } else {
                    right--;
                }
            }
        }
        return result;
    }
}
