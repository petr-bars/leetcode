package com.example.third_step.binary_search;

/**
 * <p>Given an array of integers nums which is sorted in ascending order,
 * and an integer target, write a function to search target in nums.
 * If target exists, then return its index. Otherwise, return -1.</p>
 *
 * <p>Дан отсортированный по возрастанию массив nums и число target.
 * Найти индекс target. Если его нет — вернуть -1.</p>
 *
 * <p>Пример:<br>
 * Вход:  nums = [-1,0,3,5,9,12], target = 9<br>
 * Выход: 4</p>
 *
 * <p>Паттерн:<br>
 * Бинарный поиск — деление отрезка пополам.</p>
 *
 * <p>Идея:<br>
 * Массив отсортирован. Значит, можно не смотреть все элементы подряд,
 * а отбрасывать половину на каждом шаге. Держим отрезок, где может
 * находиться target. Смотрим на середину. Если середина равна — нашли.
 * Если середина меньше target — значит, всё левее тоже меньше (массив
 * отсортирован), отбрасываем левую половину. Если больше — отбрасываем
 * правую. Каждый шаг сокращает отрезок вдвое.</p>
 *
 * <p>Логика и шаги:</p>
 * <ul>
 *   <li>Инициализация. Левая граница — начало массива, правая — конец.
 *       Отрезок пока весь массив.</li>
 *   <li>Пока отрезок не пуст (левая граница не перешла за правую):
 *       <ul>
 *         <li>Берём середину. Считаем средний индекс между границами.
 *             Формула left + (right - left) / 2 вместо (left + right) / 2,
 *             чтобы не было переполнения при больших индексах.</li>
 *         <li>Сравниваем значение в середине с target:
 *             <ul>
 *               <li>равно → нашли, возвращаем индекс середины.</li>
 *               <li>меньше → target правее, отбрасываем левую половину:
 *                   левая граница становится на шаг правее середины.</li>
 *               <li>больше → target левее, отбрасываем правую половину:
 *                   правая граница становится на шаг левее середины.</li>
 *             </ul>
 *         </li>
 *       </ul>
 *   </li>
 *   <li>Если цикл закончился — target не найден, вернуть -1.</li>
 * </ul>
 *
 * <p>Ключевая тонкость (границы):<br>
 * Когда середина меньше target, новая левая граница — это середина плюс
 * один, а не сама середина. Потому что середину мы уже проверили, она
 * не подходит. Исключать её из нового отрезка обязательно. То же с правой
 * границей — середина минус один. Если забыть этот шаг — цикл зациклится
 * на двух соседних элементах.</p>
 *
 * <p>Ключевая тонкость (условие цикла):<br>
 * Цикл идёт, пока левая граница не больше правой. Потому что отрезок из
 * одного элемента — это валидный случай, его ещё надо проверить. Если
 * поставить «строго меньше», потеряешь последний элемент.</p>
 *
 * <p>Типичные ошибки:</p>
 * <ul>
 *   <li>Не переиспользуй left под середину. Середина — отдельная переменная.
 *       left и right — только границы отрезка.</li>
 *   <li>Сравнивай nums[mid] с target, а не mid. mid — индекс, target — значение.</li>
 *   <li>Сдвигай границы за середину, а не на один шаг: left = mid + 1,
 *       right = mid - 1. Иначе это линейный поиск, а не бинарный.</li>
 *   <li>Возвращай mid без +1. LeetCode ждёт 0-based индекс.</li>
 * </ul>
 *
 * <p>Проверки:</p>
 * <ul>
 *   <li>target в середине массива.</li>
 *   <li>target в начале.</li>
 *   <li>target в конце.</li>
 *   <li>target меньше всех.</li>
 *   <li>target больше всех.</li>
 *   <li>target отсутствует, но между элементами.</li>
 *   <li>массив из одного элемента, target совпадает.</li>
 *   <li>массив из одного элемента, target не совпадает.</li>
 * </ul>
 *
 * <p>Сложность:<br>
 * Время: O(log n) — каждый шаг делит отрезок пополам.<br>
 * Память: O(1) — только указатели и середина.</p>
 */
public class BinarySearch {
    public static void main(String[] args) {
        int[] nums = new int[]{-1, 0, 3, 5, 9, 12};
        int target = 9;

        System.out.println(search(nums, target));
    }

    public static int search(int[] nums, int target) {
        int left = 0;
        int right = nums.length - 1;
        while (left <= right) {
            int mid = left + (right - left) / 2;
            if (nums[mid] == target) {
                return mid;
            } else if (nums[mid] < target) {
                left = mid + 1;
            } else {
                right = mid - 1;
            }
        }
        return -1;
    }
}
