package com.example.third_step.find_minimum_in_rotated_sorted_array;

/**
 * <p>Suppose an array of length n sorted in ascending order is rotated between 1
 * and n times. For example, the array nums = [0,1,2,4,5,6,7] might become:</p>
 *
 * <ul>
 *   <li>[4,5,6,7,0,1,2] if it was rotated 4 times.</li>
 *   <li>[0,1,2,4,5,6,7] if it was rotated 7 times.</li>
 * </ul>
 *
 * <p>Notice that rotating an array [a[0], a[1], a[2], ..., a[n-1]] 1 time results
 * in the array [a[n-1], a[0], a[1], a[2], ..., a[n-2]].</p>
 *
 * <p>Given the sorted rotated array nums of unique elements, return the minimum
 * element of this array. You must write an algorithm that runs in O(log n) time.</p>
 *
 * <p>Дан отсортированный по возрастанию массив nums (все элементы уникальны),
 * сдвинутый вправо от 1 до n раз. Например, [0,1,2,4,5,6,7] может превратиться
 * в [4,5,6,7,0,1,2] после сдвига на 4. Найти минимальный элемент массива.
 * Решение должно работать за O(log n).</p>
 *
 * <p>Пример:<br>
 * Вход:  nums = [3,4,5,1,2]<br>
 * Выход: 1</p>
 *
 * <p>Пример:<br>
 * Вход:  nums = [4,5,6,7,0,1,2]<br>
 * Выход: 0</p>
 *
 * <p>Пример:<br>
 * Вход:  nums = [11,13,15,17]<br>
 * Выход: 11</p>
 *
 * <p>Паттерн:<br>
 * Бинарный поиск по точке разрыва сортировки.</p>
 *
 * <p>Идея:<br>
 * Массив сдвинут, но не «сломан». Минимальный элемент — это точка сдвига,
 * то есть место, где сортировка разрывается. До точки сдвига все элементы
 * возрастают, после неё тоже. Значит, задача сводится к поиску места разрыва.
 * Ключевое наблюдение: если nums[mid] больше nums[right], то точка сдвига
 * (и минимум) находится правее mid. Если nums[mid] меньше nums[right] —
 * минимум находится на mid или левее. Сравнение идёт с nums[right], а не
 * с nums[left], потому что в rotated array именно правая граница даёт
 * однозначный ответ, с какой стороны разрыв.</p>
 *
 * <p>Логика и шаги:</p>
 * <ul>
 *   <li>Инициализация. left = 0, right = n - 1. Отрезок пока весь массив.</li>
 *   <li>Пока left &lt; right (не &lt;=, потому что в конце останется один элемент — он и есть минимум):
 *       <ul>
 *         <li>Берём середину. mid = left + (right - left) / 2.</li>
 *         <li>Сравниваем nums[mid] с nums[right]:
 *             <ul>
 *               <li>Если nums[mid] &gt; nums[right] → минимум строго правее mid,
 *                   потому что разрыв между mid и right. left = mid + 1.</li>
 *               <li>Иначе (nums[mid] &lt; nums[right]) → минимум на mid или левее.
 *                   right = mid.</li>
 *             </ul>
 *         </li>
 *       </ul>
 *   </li>
 *   <li>Когда left == right — это и есть минимальный элемент. Вернуть nums[left].</li>
 * </ul>
 *
 * <p>Ключевая тонкость (почему сравниваем с nums[right], а не с nums[left]):<br>
 * Если сравнивать с nums[left], то при nums[left] &lt; nums[mid] нельзя
 * однозначно сказать, где минимум — он может быть и слева, и справа. А вот
 * nums[right] — всегда «правый край отсортированной части», если разрыв
 * находится левее. Если nums[mid] &gt; nums[right] — разрыв точно правее mid.
 * Если nums[mid] &lt; nums[right] — правая часть от mid до right отсортирована,
 * значит разрыв левее mid (или на самом mid).</p>
 *
 * <p>Ключевая тонкость (right = mid, а не mid - 1):<br>
 * Когда nums[mid] &lt; nums[right], минимум может быть на mid. Поэтому
 * right = mid, а не mid - 1. Мы не исключаем mid из рассмотрения. Это
 * принципиально: если mid сам минимум, потерять его нельзя.</p>
 *
 * <p>Ключевая тонкость (почему ждём окончания цикла):<br>
 * В этой задаче нет «момента находки». Мы не ищем конкретное значение —
 * мы ищем место разрыва сортировки, где лежит минимум. Каждый шаг лишь
 * сужает отрезок, отбрасывая часть, где минимума точно нет. Минимум не
 * «находится» в какой-то момент — он остаётся последним выжившим элементом.
 * Поэтому цикл идёт, пока отрезок не сузится до одного элемента (left == right).
 * Этот единственный элемент и есть минимум, его и возвращаем.</p>
 *
 * <p>Ключевая тонкость (условие цикла):<br>
 * Цикл идёт пока left &lt; right, а не left &lt;= right. Потому что в конце
 * у нас останется один элемент — он и есть минимум. Если поставить &lt;=,
 * цикл сделает лишнюю итерацию и может сломать границы.</p>
 *
 * <p>Типичные ошибки:</p>
 * <ul>
 *   <li>Сравнивать с nums[left] вместо nums[right]. Это даёт неоднозначность
 *       и неверные результаты на некоторых сдвигах.</li>
 *   <li>Использовать right = mid - 1. Если mid сам минимум, потеряешь его.</li>
 *   <li>Использовать left = mid вместо left = mid + 1. Если mid не минимум,
 *       можно зациклиться. left должен сдвигаться за mid.</li>
 *   <li>Поставить условие цикла left &lt;= right. Сделает лишнюю итерацию.</li>
 *   <li>Пытаться вернуть результат внутри цикла. Здесь нет момента находки —
 *       минимум определяется только по окончании сужения отрезка.</li>
 *   <li>Забыть про случай без сдвига (массив уже отсортирован). В этом случае
 *       nums[mid] всегда &lt; nums[right], и right плавно сползает к 0.</li>
 * </ul>
 *
 * <p>Проверки:</p>
 * <ul>
 *   <li>сдвиг на середине массива.</li>
 *   <li>сдвиг на 1 (минимум в конце).</li>
 *   <li>без сдвига (уже отсортирован, минимум в начале).</li>
 *   <li>минимум в середине.</li>
 *   <li>массив из одного элемента.</li>
 *   <li>массив из двух элементов, сдвиг есть.</li>
 *   <li>массив из двух элементов, сдвига нет.</li>
 *   <li>массив из трёх элементов с разными сдвигами.</li>
 * </ul>
 *
 * <p>Сложность:<br>
 * Время: O(log n) — каждый шаг делит отрезок пополам.<br>
 * Память: O(1) — только границы и середина.</p>
 */
public class FindMinimumInRotatedSortedArray {
    public static void main(String[] args) {
        int[] nums = new int[]{3, 4, 5, 1, 2};

        System.out.println(findMin(nums));
    }

    public static int findMin(int[] nums) {
        int left = 0;
        int right = nums.length - 1;
        while (left < right) {
            int mid = left + (right - left) / 2;

            if (nums[mid] < nums[right]) {
                right = mid;
            } else {
                left = mid + 1;
            }
        }
        return nums[left];
    }
}
