package com.example.tenth_step.unique_paths;

import java.util.Arrays;

public class Solution {

    /**
     * Считает количество уникальных путей робота из левого верхнего угла
     * сетки {@code m × n} в правый нижний угол.
     * <p>
     * Робот может двигаться только вниз или вправо.
     * <p>
     * <b>Подход:</b> двумерное динамическое программирование (2D DP).
     * <p>
     * <b>Идея:</b> в клетку {@code (row, col)} робот может попасть только двумя способами:
     * <ul>
     *   <li>сверху — из клетки {@code (row-1, col)};</li>
     *   <li>слева — из клетки {@code (row, col-1)}.</li>
     * </ul>
     * Значит, количество путей до клетки равно сумме путей до этих двух клеток:
     * <pre>
     * dp[row][col] = dp[row-1][col] + dp[row][col-1]
     * </pre>
     * <p>
     * <b>Базовые случаи:</b>
     * <ul>
     *   <li>первая строка ({@code row == 0}) — только один путь (двигаться вправо);</li>
     *   <li>первый столбец ({@code col == 0}) — только один путь (двигаться вниз).</li>
     * </ul>
     * <p>
     * <b>Порядок заполнения:</b> слева направо, сверху вниз — чтобы значения
     * сверху и слева были уже вычислены к моменту обработки текущей клетки.
     * <p>
     * <b>Сложность:</b>
     * <ul>
     *   <li>Время: O(m × n).</li>
     *   <li>Память: O(m × n) — хранится вся таблица.</li>
     * </ul>
     *
     * @param m количество строк в сетке
     * @param n количество столбцов в сетке
     * @return количество уникальных путей из {@code (0,0)} в {@code (m-1, n-1)}
     * @see #uniquePathsOptimized(int, int)
     */
    public int uniquePaths(int m, int n) {
        int[][] dp = new int[m][n];

        for (int row = 0; row < m; row++) {
            for (int col = 0; col < n; col++) {
                if (row == 0 || col == 0) {
                    dp[row][col] = 1;
                } else {
                    dp[row][col] = dp[row - 1][col] + dp[row][col - 1];
                }
            }
        }

        return dp[m - 1][n - 1];
    }


    /**
     * Оптимизированная версия {@link #uniquePaths(int, int)} с памятью O(n).
     * <p>
     * <b>Идея оптимизации:</b> для вычисления текущей клетки нужны только два значения:
     * <ul>
     *   <li><b>сверху</b> — значение из предыдущей строки в том же столбце;</li>
     *   <li><b>слева</b> — значение из текущей строки в предыдущем столбце.</li>
     * </ul>
     * Поэтому всю таблицу хранить не нужно — достаточно одной строки длиной {@code n}.
     * <p>
     * <b>Как это работает:</b>
     * <ol>
     *   <li>Изначально массив {@code dp} заполнен единицами — это первая строка таблицы.</li>
     *   <li>Для каждой следующей строки обновляем элементы массива:
     *       <pre>
     *       dp[col] = dp[col] + dp[col - 1]
     *       </pre>
     *       где {@code dp[col]} до обновления — значение сверху,
     *       а {@code dp[col-1]} после обновления — значение слева.</li>
     *   <li>После обработки всех строк {@code dp[n-1]} содержит ответ.</li>
     * </ol>
     * <p>
     * <b>Пример для m = 3, n = 3:</b>
     * <pre>
     * Начало:         [1, 1, 1]
     * row = 1:        [1, 2, 3]
     * row = 2:        [1, 3, 6]
     * Ответ: dp[2] = 6
     * </pre>
     * <p>
     * <b>Сложность:</b>
     * <ul>
     *   <li>Время: O(m × n) — не изменилось.</li>
     *   <li>Память: O(n) — вместо {@code m × n}.</li>
     * </ul>
     *
     * @param m количество строк в сетке
     * @param n количество столбцов в сетке
     * @return количество уникальных путей из {@code (0,0)} в {@code (m-1, n-1)}
     * @see #uniquePaths(int, int)
     */
    public int uniquePathsOptimized(int m, int n) {
        int[] dp = new int[n];
        Arrays.fill(dp, 1); // первая строка — все единицы

        for (int row = 1; row < m; row++) {
            for (int col = 1; col < n; col++) {
                dp[col] = dp[col] + dp[col - 1];
            }
        }

        return dp[n - 1];
    }
}
