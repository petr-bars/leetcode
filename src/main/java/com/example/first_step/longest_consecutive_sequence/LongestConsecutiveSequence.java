package com.example.first_step.longest_consecutive_sequence;

import java.util.HashSet;
import java.util.Set;

/**
 * <p>Given an unsorted array of integers nums, return the length of the longest
 * consecutive elements sequence. You must write an algorithm that runs in O(n)
 * time.</p>
 *
 * <p>Дан неотсортированный массив целых чисел nums. Вернуть длину самой
 * длинной последовательности подряд идущих чисел (например, 1, 2, 3, 4).
 * Решение должно работать за O(n).</p>
 *
 * <p>Пример:<br>
 * Вход:  nums = [100,4,200,1,3,2]<br>
 * Выход: 4<br>
 * Пояснение: самая длинная последовательность — [1, 2, 3, 4], длина 4.</p>
 *
 * <p>Пример:<br>
 * Вход:  nums = [0,3,7,2,5,8,4,6,0,1]<br>
 * Выход: 9<br>
 * Пояснение: [0,1,2,3,4,5,6,7,8], длина 9.</p>
 *
 * <p>Паттерн:<br>
 * HashSet + проверка начала последовательности.</p>
 *
 * <p>Именование переменных:<br>
 * set — HashSet со всеми уникальными числами из массива. Нужен для проверки
 * «есть ли такое число» за O(1) и для устранения дубликатов. item — текущий
 * элемент итерации по set. current — рабочая переменная, которая двигается
 * вправо по последовательности. count — длина текущей найденной
 * последовательности. best — длина самой длинной последовательности
 * за весь проход.</p>
 *
 * <p>Идея:<br>
 * Сортировка решает задачу за O(n log n), но условие требует O(n). Значит,
 * сортировать нельзя. Вместо этого кладём все числа в HashSet — это даёт
 * проверку «есть ли число» за O(1) и убирает дубликаты. Дальше главная
 * хитрость: считать длину последовательности только от её начала. Число
 * является началом, если числа item - 1 в set нет. От каждого начала
 * идём вправо через while, пока есть item + 1, item + 2, и так далее.
 * Каждое число принадлежит ровно одной последовательности и посещается
 * только один раз — от её начала. Это и даёт O(n).</p>
 *
 * <p>Логика и шаги:</p>
 * <ul>
 *   <li>Создаём HashSet set и кладём в него все числа из массива nums.
 *       Дубликаты отсеиваются автоматически.</li>
 *   <li>best = 0 — текущий максимум длины.</li>
 *   <li>Идём по set, берём каждый item:
 *       <ul>
 *         <li>Проверяем: есть ли item - 1 в set?
 *             <ul>
 *               <li>Да → это не начало последовательности. Пропускаем.
 *                   Эту последовательность посчитают, когда дойдут до её
 *                   настоящего начала.</li>
 *               <li>Нет → это начало последовательности. Начинаем считать
 *                   длину.</li>
 *             </ul>
 *         </li>
 *         <li>Если начало:
 *             <ul>
 *               <li>count = 1. Само item уже часть последовательности.</li>
 *               <li>current = item. Рабочая переменная для движения вправо.</li>
 *               <li>Пока set.contains(current + 1):
 *                   <ul>
 *                     <li>count++.</li>
 *                     <li>current++.</li>
 *                   </ul>
 *               </li>
 *               <li>После while: count — длина последовательности от item.</li>
 *               <li>best = max(best, count).</li>
 *             </ul>
 *         </li>
 *       </ul>
 *   </li>
 *   <li>После цикла возвращаем best.</li>
 * </ul>
 *
 * <p>Ключевые тонкости:</p>
 * <ul>
 *   <li>Итерируемся по set, а не по массиву. В массиве есть дубликаты —
 *       одно и то же число обрабатывалось бы несколько раз. В set каждое
 *       число уникально, обрабатывается ровно один раз.</li>
 *   <li>Проверка item - 1 — ключевая для O(n). Без неё внутренний while
 *       запускался бы от каждого числа, и суммарно получилось бы O(n²).
 *       С ней — только от начал, и каждое число внутри while посещается
 *       один раз.</li>
 *   <li>count начинается с 1, а не с 0. Потому что само item уже часть
 *       последовательности. Если начать с 0, для одиночного числа (у которого
 *       нет соседей) получишь 0 вместо 1.</li>
 *   <li>best обновляется ВНУТРИ if, после while. Если обновлять снаружи if,
 *       для не-начал (где count всегда 1) будет лишний вызов Math.max.
 *       Если обновлять внутри while — потеряешь одиночные числа, потому что
 *       while для них не выполнится ни разу. Правильное место — после while,
 *       но внутри if.</li>
 *   <li>current — отдельная переменная, а не item. Изменять item внутри
 *       for-each нельзя (компилятор не даст). current двигается вправо,
 *       item остаётся элементом set.</li>
 *   <li>Используем set.contains(current + 1), а не set.contains(current) + 1.
 *       Скобки важны: сначала проверяем наличие числа, только потом двигаем
 *       счётчик.</li>
 *   <li>Пустой массив — set пустой, цикл не выполнится, вернётся 0.</li>
 *   <li>Массив из одного числа — set из одного числа, оно начало (item - 1
 *       нет), while не выполнится, count = 1, best = 1. Вернётся 1.</li>
 *   <li>Все числа одинаковые — set из одного числа, вернётся 1.</li>
 *   <li>Числа идут строго подряд — от минимального (единственного начала)
 *       считаем всю длину сразу, получаем n.</li>
 * </ul>
 *
 * <p>Проверки:</p>
 * <ul>
 *   <li>nums = [100,4,200,1,3,2] → 4 (последовательность 1,2,3,4).</li>
 *   <li>nums = [0,3,7,2,5,8,4,6,0,1] → 9 (0..8).</li>
 *   <li>nums = [] → 0. Пустой массив.</li>
 *   <li>nums = [1] → 1. Одно число.</li>
 *   <li>nums = [1,2,3,4,5] → 5. Уже отсортирован, но это не важно.</li>
 *   <li>nums = [5,4,3,2,1] → 5. Обратный порядок.</li>
 *   <li>nums = [1,1,1,1] → 1. Дубликаты.</li>
 *   <li>nums = [1,3,5,7] → 1. Нет соседей ни у одного.</li>
 *   <li>nums = [-1,0,1] → 3. Отрицательные числа.</li>
 *   <li>nums = [-2,-1,0,1,2] → 5. Смешанные.</li>
 *   <li>nums = [Integer.MIN_VALUE, Integer.MAX_VALUE] → 1. Границы int.</li>
 * </ul>
 *
 * <p>Сложность:<br>
 * Время: O(n) — вставка в set O(n), внешний цикл O(n), суммарно внутренний
 *       while по всем последовательностям не превышает O(n), потому что
 *       каждое число принадлежит ровно одной последовательности и посещается
 *       только из её начала.<br>
 * Память: O(n) — HashSet хранит все уникальные числа.</p>
 */
public class LongestConsecutiveSequence {
    public static void main(String[] args) {
        int[] nums = new int[]{100, 4, 200, 1, 1, 1, 3, 2};
//        int[] nums = new int[]{1, 2, 3, 4, 5, 10, 11, 20, 21, 22, 23, 24, 25};

        System.out.println(longestConsecutiveWithHashSet(nums));

    }

    public static int longestConsecutiveWithHashSet(int[] nums) {
        Set<Integer> set = new HashSet<>();
        for (int num : nums) {
            set.add(num);
        }

        int best = 0;
        for (int item : set) {
            if (!set.contains(item - 1)) {
                int count = 1;
                int current = item;
                while (set.contains(current + 1)) {
                    count++;
                    current++;
                }
                best = Math.max(best, count);
            }
        }

        return best;
    }
}
