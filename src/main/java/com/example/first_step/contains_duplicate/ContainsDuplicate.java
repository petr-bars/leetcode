package com.example.first_step.contains_duplicate;

import java.util.HashSet;
import java.util.Set;

/**
 * <p>Given an integer array nums, return true if any value appears at least
 * twice in the array, and return false if every element is distinct.</p>
 *
 * <p>Дан массив целых чисел nums. Вернуть true, если хотя бы одно значение
 * встречается два раза или больше. Вернуть false, если все элементы
 * уникальны.</p>
 *
 * <p>Пример:<br>
 * Вход:  nums = [1,2,3,1]<br>
 * Выход: true</p>
 *
 * <p>Пример:<br>
 * Вход:  nums = [1,2,3,4]<br>
 * Выход: false</p>
 *
 * <p>Пример:<br>
 * Вход:  nums = [1,1,1,3,3,4,3,2,4,2]<br>
 * Выход: true</p>
 *
 * <p>Паттерн:<br>
 * Хеш-множество (HashSet) для проверки дубликатов.</p>
 *
 * <p>Именование переменных:<br>
 * seen — HashSet, в который складываем все числа, которые уже прошли.
 * Служит для проверки «встречалось ли это число раньше». num — текущее
 * число из массива.</p>
 *
 * <p>Идея:<br>
 * Нужно понять, есть ли в массиве повтор. Наивно — сравнить каждую пару,
 * но это O(n²). Быстрее — держать множество уже увиденных чисел. Set
 * не хранит дубликаты по определению: если попытаться добавить число,
 * которое уже есть, добавление не произойдёт. Это свойство и используем.
 * Идём по массиву, пытаемся добавить каждое число в seen. Если добавление
 * не удалось — число уже было, значит дубликат найден.</p>
 *
 * <p>Логика и шаги:</p>
 * <ul>
 *   <li>Создаём пустой HashSet seen.</li>
 *   <li>Идём по массиву nums, берём каждое число num:
 *       <ul>
 *         <li>Пытаемся добавить num в seen через метод add.</li>
 *         <li>Метод add возвращает true, если число добавлено (его не было),
 *             и false, если число уже было в множестве.</li>
 *         <li>Если add вернул false → дубликат найден. Возвращаем true
 *             сразу, не досматривая массив.</li>
 *       </ul>
 *   </li>
 *   <li>Если цикл закончился и ни один add не вернул false — все числа
 *       уникальны. Возвращаем false.</li>
 * </ul>
 *
 * <p>Ключевые тонкости:</p>
 * <ul>
 *   <li>Метод add возвращает boolean, а не void. Это позволяет проверить
 *       «было ли число раньше» одним вызовом, без отдельного contains.
 *       Обычно contains + add — это два обращения к множеству, а тут
 *       хватает одного.</li>
 *   <li>Условие в if — !seen.add(num). Читается как «не удалось добавить».
 *       Если записать seen.add(num) == false, смысл тот же, но запись
 *       с отрицанием короче и привычнее.</li>
 *   <li>Ранний возврат true при первой находке. Нет смысла идти дальше —
 *       ответ уже известен.</li>
 *   <li>HashSet, а не HashMap. Нам не нужно хранить индексы или другую
 *       информацию — только сам факт «число уже встречалось». Set для
 *       этого и предназначен.</li>
 *   <li>Дубликаты могут быть разбросаны по массиву, не обязательно рядом.
 *       Set это ловит, потому что хранит все пройденные числа, а не только
 *       соседние.</li>
 *   <li>Пустой массив — цикл не выполнится, вернётся false. Все элементы
 *       (ноль элементов) уникальны — это корректно.</li>
 *   <li>Массив из одного элемента — цикл выполнится один раз, add вернёт
 *       true, вернётся false. Один элемент уникален — корректно.</li>
 * </ul>
 *
 * <p>Проверки:</p>
 * <ul>
 *   <li>nums = [1,2,3,1] → true. Дубликат в начале и в конце.</li>
 *   <li>nums = [1,2,3,4] → false. Все уникальны.</li>
 *   <li>nums = [1,1,1,3,3,4,3,2,4,2] → true. Много дубликатов.</li>
 *   <li>nums = [1] → false. Один элемент.</li>
 *   <li>nums = [] → false. Пустой массив.</li>
 *   <li>nums = [1,1] → true. Минимальный дубликат.</li>
 *   <li>nums = [-1,-2,-3,-1] → true. Отрицательные числа.</li>
 *   <li>nums = [0,0] → true. Нули.</li>
 *   <li>nums = [Integer.MIN_VALUE, Integer.MAX_VALUE] → false. Границы int.</li>
 *   <li>nums = [1000000000, -1000000000, 1000000000] → true. Большие числа.</li>
 * </ul>
 *
 * <p>Сложность:<br>
 * Время: O(n) — один проход по массиву, каждая операция add в HashSet
 *       в среднем за O(1).<br>
 * Память: O(n) — HashSet хранит до n элементов в худшем случае
 *         (когда все уникальны).</p>
 */
public class ContainsDuplicate {
    public static void main(String[] args) {
//        int[] nums = new int[]{1, 1, 1, 3, 3, 4, 3, 2, 4, 2};
//        int[] nums = new int[]{2,14,18,22,22};
//        int[] nums = new int[]{1, 2, 3, 1, 5};
        int[] nums = new int[]{1, 2, 3, 7, 5};
        System.out.println(containsDuplicate(nums));
    }

    public static boolean containsDuplicate(int[] nums) {
        Set<Integer> seen = new HashSet<>();
        for (int num : nums) {
            if (!seen.add(num)) {
                return true;
            }
        }
        return false;
    }
}
