package com.example.first_step.maximum_subarray;

/**
 * <p>Given an integer array nums, find the subarray with the largest sum,
 * and return its sum.</p>
 *
 * <p>Дан целочисленный массив nums. Найти непрерывный подмассив (содержащий
 * хотя бы одно число) с максимальной суммой и вернуть эту сумму.</p>
 *
 * <p>Пример:<br>
 * Вход:  nums = [-2,1,-3,4,-1,2,1,-5,4]<br>
 * Выход: 6<br>
 * Пояснение: подмассив [4,-1,2,1] даёт сумму 6.</p>
 *
 * <p>Пример:<br>
 * Вход:  nums = [1]<br>
 * Выход: 1</p>
 *
 * <p>Пример:<br>
 * Вход:  nums = [5,4,-1,7,8]<br>
 * Выход: 23<br>
 * Пояснение: подмассив [5,4,-1,7,8] целиком.</p>
 *
 * <p>Паттерн:<br>
 * Алгоритм Кадане (Kadane's algorithm). Это 1D DP: идём по массиву и на
 * каждом шаге решаем — продолжить текущий подмассив или начать новый.</p>
 *
 * <p>Именование переменных:<br>
 * maxSum — лучшая сумма подмассива, найденная за весь проход. Начинается
 * со значения первого элемента (а не с 0 — потому что массив может быть
 * полностью отрицательным). currentSum — сумма подмассива, который
 * заканчивается на текущем элементе. num — текущий элемент в цикле.</p>
 *
 * <p>Идея:<br>
 * Нужно найти непрерывный подмассив с максимальной суммой. Наивно —
 * перебрать все подмассивы, это O(n²) или O(n³). Алгоритм Кадане решает
 * за O(n): на каждом элементе рассматриваем два варианта — продолжить
 * текущий подмассив или начать новый с этого элемента. Если накопленная
 * сумма отрицательная, она только тянет результат вниз — выгоднее начать
 * заново с текущего числа. Берём максимум из двух вариантов и обновляем
 * общий максимум.</p>
 *
 * <p>Логика и шаги:</p>
 * <ul>
 *   <li>Инициализация:
 *       <ul>
 *         <li>maxSum = nums[0]. Почему не 0: массив может быть полностью
 *             отрицательным (например, [-3,-1,-5]). Тогда правильный ответ
 *             — самое большое отрицательное число, а не 0. Если начать
 *             с 0, вернёшь 0 для такого массива, что неверно.</li>
 *         <li>currentSum = 0. Начинаем «без накопленной суммы», первый
 *             элемент сразу даст currentSum = nums[0].</li>
 *       </ul>
 *   </li>
 *   <li>Проход по массиву:
 *       <ul>
 *         <li>Для каждого num:
 *             <ul>
 *               <li>currentSum = max(num, currentSum + num). Если
 *                   накопленная сумма + текущий элемент больше самого
 *                   элемента — продолжаем. Если меньше — начинаем
 *                   заново с текущего элемента.</li>
 *               <li>maxSum = max(maxSum, currentSum). Обновляем лучший
 *                   результат.</li>
 *             </ul>
 *         </li>
 *       </ul>
 *   </li>
 *   <li>Возвращаем maxSum.</li>
 * </ul>
 *
 * <p>Ключевые тонкости:</p>
 * <ul>
 *   <li>maxSum инициализируется nums[0], а не 0. Это критично для случая,
 *       когда все числа отрицательные. Пример: nums = [-3,-1,-5]. Если
 *       maxSum = 0, вернётся 0. А правильный ответ — (-1), потому что
 *       подмассив должен содержать хотя бы одно число, и максимальная
 *       сумма среди одноэлементных подмассивов = -1.</li>
 *   <li>currentSum = max(num, currentSum + num) — та же логика, но не
 *       через if. Если currentSum отрицательный, то currentSum + num
 *       меньше num, и max выберет num — начинаем заново. Если
 *       currentSum положительный — продолжаем, потому что накопленная
 *       сумма увеличивает результат.</li>
 *   <li>Порядок операций: сначала обновляем currentSum, потом maxSum.
 *       Порядок не критичен (maxSum зависит от нового currentSum),
 *       но лучше сначала считать currentSum — тогда maxSum сразу получает
 *       актуальное значение.</li>
 *   <li>Пустой массив не обрабатывается — nums[0] упадёт. По условиям
 *       LeetCode n >= 1, так что защита не нужна. Если хочешь надёжности,
 *       добавь проверку в начале.</li>
 *   <li>Алгоритм не находит сам подмассив, только его сумму. Если нужен
 *       подмассив — надо дополнительно запоминать start и end.
 *       Задача просит только сумму.</li>
 *   <li>Отрицательные числа на краях подмассива «отрезаются» сами собой:
 *       если currentSum уходит в минус, следующий шаг начнёт заново
 *       с более выгодного места.</li>
 *   <li>Альтернативная формулировка currentSum через if:
 *       «если currentSum &lt; 0, то currentSum = num, иначе currentSum += num».
 *       Эквивалентно Math.max-версии. Но Math.max компактнее и без ветвлений.</li>
 * </ul>
 *
 * <p>Проверки:</p>
 * <ul>
 *   <li>nums = [-2,1,-3,4,-1,2,1,-5,4] → 6. Подмассив [4,-1,2,1].</li>
 *   <li>nums = [1] → 1. Один элемент.</li>
 *   <li>nums = [5,4,-1,7,8] → 23. Весь массив.</li>
 *   <li>nums = [-1] → -1. Один отрицательный элемент.</li>
 *   <li>nums = [-3,-1,-5] → -1. Все отрицательные, максимум из них.</li>
 *   <li>nums = [-2,-1] → -1. Все отрицательные.</li>
 *   <li>nums = [1,2,3,4] → 10. Все положительные, весь массив.</li>
 *   <li>nums = [-1,0,-2] → 0. Ноль больше всех отрицательных.</li>
 *   <li>nums = [0] → 0.</li>
 *   <li>nums = [8,-19,5,-4,20] → 21. Подмассив [5,-4,20].</li>
 *   <li>nums = [-2,1] → 1.</li>
 *   <li>nums = [1,-1] → 1.</li>
 * </ul>
 *
 * <p>Сложность:<br>
 * Время: O(n) — один проход по массиву.<br>
 * Память: O(1) — только maxSum и currentSum.</p>
 */
public class MaximumSubarray {
    public static void main(String[] args) {
//        int[] nums = new int[]{-2, 1, -3, 4, -1, 2, 1, -5, 4};
        int[] nums = new int[]{4, -1, 2, 1};

        System.out.println(maxSubArray(nums));
    }

    public static int maxSubArray(int[] nums) {
        int maxSum = nums[0];
        int currentSum = 0;
        for (int num : nums) {
            currentSum = Math.max(num, currentSum + num);
            maxSum = Math.max(maxSum, currentSum);
        }
        return maxSum;
    }
}
