package com.example.final_bonus.single_number;

public class Solution {

    /**
     * Находит единственное число в массиве, которое встречается ровно один раз,
     * при условии, что все остальные числа встречаются ровно дважды.
     * <p>
     * <b>Подход:</b> битовая операция XOR (исключающее ИЛИ).
     * <p>
     * <b>Идея:</b> операция XOR обладает тремя ключевыми свойствами:
     * <ol>
     *   <li>{@code x ^ x = 0} — одинаковые числа взаимно уничтожаются;</li>
     *   <li>{@code x ^ 0 = x} — ноль не изменяет число;</li>
     *   <li>XOR коммутативен и ассоциативен — порядок применения не важен.</li>
     * </ol>
     * Если применить XOR ко всем элементам массива, каждая пара одинаковых чисел
     * превратится в 0, а единственное число, не имеющее пары, останется
     * единственным ненулевым слагаемым.
     * <p>
     * <b>Пример:</b>
     * <pre>
     * nums = [4, 1, 2, 1, 2]
     *
     * 4 ^ 1 ^ 2 ^ 1 ^ 2
     * = 4 ^ (1 ^ 1) ^ (2 ^ 2)
     * = 4 ^ 0 ^ 0
     * = 4
     * </pre>
     * <p>
     * <b>Алгоритм:</b>
     * <ol>
     *   <li>Заводится переменная {@code result = 0}.</li>
     *   <li>Проходим по всем элементам массива и выполняем
     *       {@code result = result ^ num}.</li>
     *   <li>После цикла {@code result} содержит искомое число.</li>
     * </ol>
     * <p>
     * <b>Сложность:</b>
     * <ul>
     *   <li>Время: O(n) — один проход по массиву.</li>
     *   <li>Память: O(1) — используется только одна переменная.</li>
     * </ul>
     * <p>
     * <b>Преимущества перед альтернативами:</b>
     * <ul>
     *   <li><b>HashMap / HashSet:</b> требуют O(n) дополнительной памяти
     *       для подсчёта частот, что нарушает требование задачи.</li>
     *   <li><b>Сортировка:</b> O(n log n) по времени, тоже не подходит.</li>
     *   <li><b>XOR:</b> удовлетворяет обоим требованиям — линейное время
     *       и константная память.</li>
     * </ul>
     *
     * @param nums непустой массив целых чисел, где каждое число, кроме одного,
     *             встречается ровно дважды
     * @return единственное число, встречающееся в массиве один раз
     * @see <a href="https://leetcode.com/problems/single-number/">LeetCode 136</a>
     */
    public int singleNumber(int[] nums) {
        int result = 0;

        for (int num : nums) {
            result ^= num;
        }

        return result;
    }
}
