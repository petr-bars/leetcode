package com.example.final_bonus.single_number_II;

public class Solution {

    /**
     * Находит единственное число в массиве, которое встречается ровно один раз,
     * при условии, что все остальные числа встречаются ровно трижды.
     * <p>
     * <b>Подход:</b> подсчёт битов по модулю 3 (Bit Counting / Bit Manipulation).
     * <p>
     * <b>Почему не XOR:</b>
     * В задаче Single Number I (повторы дважды) работал XOR, потому что
     * {@code x ^ x = 0} взаимно уничтожал пары. Здесь же {@code x ^ x ^ x = x},
     * то есть тройка не исчезает — XOR всех чисел даст неверный ответ.
     * Поэтому нужен другой подход.
     * <p>
     * <b>Идея:</b> любое число в памяти представлено набором битов (0 и 1).
     * Если каждое число (кроме одного) встречается трижды, то каждый его бит
     * тоже встречается трижды. Значит, если просуммировать значения каждого бита
     * по всем числам массива, получим:
     * <pre>
     * сумма_бита = 3 × (количество троек с этим битом) + (бит уникального числа)
     * </pre>
     * Взяв остаток по модулю 3:
     * <ul>
     *   <li>{@code сумма_бита % 3 == 0} → бит не принадлежит уникальному числу;</li>
     *   <li>{@code сумма_бита % 3 == 1} → бит принадлежит уникальному числу.</li>
     * </ul>
     * <p>
     * <b>Алгоритм:</b>
     * <ol>
     *   <li>Создаётся массив {@code counter} из 32 элементов — по одному
     *       на каждый бит целого числа (int в Java — 32 бита).</li>
     *   <li>Для каждого числа {@code num} из массива:
     *     <ul>
     *       <li>Для каждой позиции бита от 0 до 31:
     *         <ul>
     *           <li>Извлекается значение бита: {@code (num >> bitIndex) & 1}.</li>
     *           <li>Если бит равен 1 — увеличивается {@code counter[bitIndex]}.</li>
     *         </ul>
     *       </li>
     *     </ul>
     *   </li>
     *   <li>Собирается результат:
     *     <ul>
     *       <li>Для каждой позиции бита от 0 до 31:
     *         <ul>
     *           <li>Если {@code counter[bitIndex] % 3 != 0} — этот бит
     *               принадлежит уникальному числу, и он включается в результат
     *               через {@code result |= (1 << bitIndex)}.</li>
     *         </ul>
     *       </li>
     *     </ul>
     *   </li>
     *   <li>Возвращается {@code result}.</li>
     * </ol>
     * <p>
     * <b>Битовые операции, используемые в решении:</b>
     * <ul>
     *   <li>{@code num >> bitIndex} — сдвиг битов вправо, чтобы нужный бит
     *       оказался на позиции 0.</li>
     *   <li>{@code ... & 1} — маска, оставляющая только младший бит
     *       (значение 0 или 1).</li>
     *   <li>{@code 1 << bitIndex} — маска с единицей на позиции {@code bitIndex};
     *       создаёт вес этой позиции (1, 2, 4, 8, ...).</li>
     *   <li>{@code result |= mask} — включает бит в результат. Поскольку
     *       каждая позиция обрабатывается один раз, OR работает как накопление
     *       весов позиций.</li>
     * </ul>
     * <p>
     * <b>Пример:</b>
     * <pre>
     * nums = [2, 2, 3, 2]
     *
     * 2 = 10, 3 = 11
     *
     * После прохода по всем числам:
     *   counter[0] = 1   (бит 0 встречался один раз: только у 3)
     *   counter[1] = 4   (бит 1 встречался четыре раза: у всех чисел)
     *
     * Сборка:
     *   counter[0] % 3 = 1 → включаем бит 0 → result |= 1 → result = 1
     *   counter[1] % 3 = 1 → включаем бит 1 → result |= 2 → result = 3
     *
     * Ответ: 3
     * </pre>
     * <p>
     * <b>Сложность:</b>
     * <ul>
     *   <li>Время: O(32 × n) = O(n), где n — длина массива. Внутренний цикл
     *       по 32 битам фиксирован и не зависит от n.</li>
     *   <li>Память: O(1) — массив {@code counter} фиксированного размера (32),
     *       не зависит от размера входных данных.</li>
     * </ul>
     * <p>
     * <b>Ограничение применимости:</b>
     * Алгоритм корректен только если все числа, кроме одного, имеют
     * <b>одинаковую</b> кратность k (здесь k = 3), а уникальное число
     * встречается ровно один раз. При нарушении этого условия (например,
     * если одно число встречается 3 раза, а другое — 4) алгоритм даст
     * неверный результат. В общем случае вместо {@code % 3} используется
     * {@code % k}.
     * <p>
     * <b>Альтернатива:</b> существует более компактное решение через две
     * переменные {@code ones} и {@code twos}, использующее только битовые
     * операции без массива счётчиков. Оно эффективнее по константам,
     * но менее наглядно для понимания.
     *
     * @param nums массив целых чисел, в котором каждое число, кроме одного,
     *             встречается ровно трижды, а одно — ровно один раз
     * @return единственное число, встречающееся в массиве один раз
     * @see <a href="https://leetcode.com/problems/single-number-ii/">LeetCode 137</a>
     */
    public int singleNumber(int[] nums) {
        int[] counter = new int[32];

        for (int num : nums) {
            for (int bitPosition = 0; bitPosition < counter.length; bitPosition++) {
                int bit = (num >> bitPosition) & 1;
                if (bit == 1) {
                    counter[bitPosition]++;
                }
            }
        }

        int result = 0;
        for (int bitPosition = 0; bitPosition < counter.length; bitPosition++) {
            if (counter[bitPosition] % 3 != 0) {
                result |= (1 << bitPosition);
            }
        }
        return result;
    }
}
