package com.example.final_bonus.number_of_1_bits;

public class Solution {

    /**
     * Подсчитывает количество единичных битов в двоичном представлении числа {@code n}
     * (вес Хэмминга) с помощью простого перебора всех 32 битов.
     * <p>
     * <b>Подход:</b> последовательный перебор битов от младшего к старшему.
     * <p>
     * <b>Идея:</b> для каждой позиции {@code bitPosition} от 0 до 31:
     * <ol>
     *   <li>Сдвигаем число {@code n} вправо на {@code bitPosition} позиций,
     *       чтобы нужный бит оказался на позиции 0.</li>
     *   <li>Применяем маску {@code & 1}, чтобы оставить только этот бит.</li>
     *   <li>Если результат равен 1 — увеличиваем счётчик.</li>
     * </ol>
     * <p>
     * <b>Пример:</b>
     * <pre>
     * n = 11 (1011)
     *
     * bitPosition = 0: (11 >> 0) & 1 = 1 → count = 1
     * bitPosition = 1: (11 >> 1) & 1 = 1 → count = 2
     * bitPosition = 2: (11 >> 2) & 1 = 0 → count = 2
     * bitPosition = 3: (11 >> 3) & 1 = 1 → count = 3
     * bitPosition = 4..31: все нули → count не меняется
     *
     * Ответ: 3
     * </pre>
     * <p>
     * <b>Сложность:</b>
     * <ul>
     *   <li>Время: O(32) = O(1) — всегда 32 итерации, независимо от числа.</li>
     *   <li>Память: O(1) — только одна переменная-счётчик.</li>
     * </ul>
     * <p>
     * <b>Когда использовать:</b> когда важна простота и наглядность,
     * либо когда количество единиц заранее неизвестно и может быть большим.
     *
     * @param n целое число (в Java int знаковый, но здесь трактуется
     *          как беззнаковое 32-битное)
     * @return количество единичных битов в двоичном представлении числа
     * @see #hammingWeightKernighan(int)
     */
    public int hammingWeight(int n) {
        int count = 0;
        for (int bitPosition = 0; bitPosition < 32; bitPosition++) {
            int bit = (n >> bitPosition) & 1;
            if (bit == 1) {
                count++;
            }
        }
        return count;
    }


    /**
     * Подсчитывает количество единичных битов в двоичном представлении числа {@code n}
     * (вес Хэмминга) с помощью алгоритма Кернигана.
     * <p>
     * <b>Подход:</b> использование трюка {@code n & (n - 1)}, который удаляет
     * самую младшую единицу из числа за одну операцию.
     * <p>
     * <b>Идея:</b>
     * <ol>
     *   <li>Операция {@code n - 1} меняет самый правый единичный бит на 0,
     *       а все нули справа от него — на 1.</li>
     *   <li>Побитовое И {@code n & (n - 1)} стирает эту самую правую единицу,
     *       оставляя остальные биты без изменений.</li>
     *   <li>Повторяем, пока {@code n != 0}, считая количество итераций.</li>
     *   <li>Количество итераций равно количеству единичных битов.</li>
     * </ol>
     * <p>
     * <b>Пример:</b>
     * <pre>
     * n = 11 (1011)
     *
     * Итерация 1: n = 1011, n-1 = 1010, n & (n-1) = 1010, count = 1
     * Итерация 2: n = 1010, n-1 = 1001, n & (n-1) = 1000, count = 2
     * Итерация 3: n = 1000, n-1 = 0111, n & (n-1) = 0000, count = 3
     * n == 0 → стоп.
     *
     * Ответ: 3
     * </pre>
     * <p>
     * <b>Сложность:</b>
     * <ul>
     *   <li>Время: O(k), где k — количество единичных битов.
     *       В худшем случае k = 32, но в среднем быстрее, чем перебор всех битов.</li>
     *   <li>Память: O(1) — только одна переменная-счётчик.</li>
     * </ul>
     * <p>
     * <b>Преимущества:</b>
     * <ul>
     *   <li>Не делает лишних итераций, если единиц мало.</li>
     *   <li>Работает с отрицательными числами благодаря битовому представлению
     *       (two's complement).</li>
     * </ul>
     * <p>
     * <b>Когда использовать:</b> когда важна эффективность, особенно для чисел
     * с малым количеством единиц. Это классический приём на собеседованиях.
     *
     * @param n целое число (в Java int знаковый, но здесь трактуется
     *          как беззнаковое 32-битное)
     * @return количество единичных битов в двоичном представлении числа
     * @see #hammingWeight(int)
     */
    public int hammingWeightKernighan(int n) {
        int count = 0;
        while (n != 0) {
            n = n & (n - 1);
            count++;
        }
        return count;
    }
}